"""
Список тем для ежедневных постов — ротация по дню года, чтобы темы не
повторялись подряд и не нужно было ничего вести вручную.
"""
import datetime as dt

import gemini_client

TOPICS = [
    ("Принцип тарелки вместо подсчёта калорий",
     "тёплая тарелка еды, разделённая на секции — овощи, белок, крупа, вид сверху"),
    ("Медленная и осознанная еда",
     "человек спокойно ест за столом без телефона, уютная кухня, тёплый свет"),
    ("Сон и его влияние на аппетит",
     "уютная спальня, мягкий свет, ощущение спокойствия перед сном"),
    ("Бытовая активность вместо тренировок",
     "человек идёт пешком по осенней улице с чашкой чая, лёгкость и движение"),
    ("Вода и клетчатка вместо голодания",
     "стакан воды и тарелка свежих овощей и фруктов на столе"),
    ("Баланс вместо жёстких запретов",
     "тарелка с небольшим кусочком десерта рядом со свежими фруктами, гармония"),
    ("Что делать, если сорвались с плана",
     "спокойное утро, чашка чая у окна, ощущение нового начала без вины"),
    ("Мифы о похудении, в которые пора перестать верить",
     "весы и сантиметр на столе в мягком, немного ироничном освещении"),
    ("Как справляться со стрессом без заедания",
     "человек дышит у открытого окна, растения на подоконнике, спокойствие"),
    ("Маленькие привычки, которые работают лучше жёстких диет",
     "записная книжка с отмеченными галочками привычек, чашка чая рядом"),
]


def get_today_topic() -> tuple[str, str]:
    day_index = dt.date.today().timetuple().tm_yday
    return TOPICS[day_index % len(TOPICS)]


def build_daily_draft() -> dict:
    """Генерирует текст + картинку для поста дня. Возвращает dict для сохранения в БД."""
    topic_prompt, image_prompt = get_today_topic()
    text = gemini_client.generate_tip_text(topic_prompt)
    image_bytes = gemini_client.generate_image(image_prompt)
    return {
        "topic": topic_prompt,
        "text": text,
        "image_bytes": image_bytes,
    }
